const PI = Math.PI
const FFT_FIXED_POINT_SCALE = 32768

/**
 * Clamp one rounded transform coefficient to signed 16-bit storage.
 *
 * @param {number} value
 * @returns {number}
 */
function clampInt16(value) {
  return Math.max(-0x8000, Math.min(0x7fff, value))
}

/**
 * Build every runtime transform table with pinned rounding behavior.
 *
 * @returns {object}
 */
function buildTransformTables() {
  const tables = {
    mdctPreRotationCosines: new Float32Array(128),
    mdctPreRotationSines: new Float32Array(128),
    mdctBaseCosineMinusFifthSine: new Float32Array(128),
    mdctBaseCosinePlusFifthSine: new Float32Array(128),
    mdctFifthCosinePlusBaseSine: new Float32Array(128),
    mdctFifthCosineMinusBaseSine: new Float32Array(128),
    mdctTwiddleCosines: new Float32Array(64),
    mdctTwiddleSines: new Float32Array(64),
    mdctBitReversalIndices: new Uint32Array(128),
    mdctWindow: new Float32Array(512),
    fftStagedCosines: new Int16Array(127),
    fftStagedSines: new Int16Array(127),
    fftFinalCosines: new Int16Array(128),
    fftFinalSines: new Int16Array(128),
    fftGrayBitReversalIndices: new Uint8Array(256),
  }

  for (let index = 0; index < 128; index++) {
    const angle = (index * PI) / 128
    tables.mdctPreRotationCosines[index] = Math.cos(angle)
    tables.mdctPreRotationSines[index] = -Math.sin(angle)
  }

  for (let index = 0; index < 64; index++) {
    const angle = (index * PI) / 64
    tables.mdctTwiddleCosines[index] = Math.cos(angle)
    tables.mdctTwiddleSines[index] = -Math.sin(angle)
  }

  const halfPiCosine = float32FromBits(0x248d3000)
  tables.mdctPreRotationCosines[64] = halfPiCosine
  tables.mdctTwiddleCosines[32] = halfPiCosine

  for (let index = 0; index < 128; index++) {
    tables.mdctBitReversalIndices[index] = reverseLowBits(index, 7)
  }

  for (let index = 0; index < 512; index++) {
    const sine = Math.sin(((2 * index + 1) * PI) / 1024)
    tables.mdctWindow[index] = sine * sine
  }

  for (let index = 0; index < 128; index++) {
    const angleBase = ((2 * index + 1) * PI) / 1024
    const angleFifth = ((10 * index + 5) * PI) / 1024
    const cosineBase = Math.cos(angleBase)
    const sineBase = Math.sin(angleBase)
    const fifthCosine = Math.cos(angleFifth)
    const fifthSine = Math.sin(angleFifth)
    tables.mdctBaseCosineMinusFifthSine[index] = 0.5 * (cosineBase - fifthSine)
    tables.mdctBaseCosinePlusFifthSine[index] = 0.5 * (cosineBase + fifthSine)
    tables.mdctFifthCosinePlusBaseSine[index] = 0.5 * (fifthCosine + sineBase)
    tables.mdctFifthCosineMinusBaseSine[index] = 0.5 * (fifthCosine - sineBase)
  }

  let tableIndex = 0
  for (let stage = 0; stage < 7; stage++) {
    const size = 2 ** stage
    const denominator = 2 ** (stage + 2)
    for (let stageIndex = 0; stageIndex < size; stageIndex++) {
      const angle = ((4 * stageIndex + 1) * PI) / denominator
      tables.fftStagedSines[tableIndex] = clampInt16(
        Math.trunc(Math.sin(angle) * FFT_FIXED_POINT_SCALE)
      )
      tables.fftStagedCosines[tableIndex] = clampInt16(
        Math.floor(Math.cos(angle) * FFT_FIXED_POINT_SCALE)
      )
      tableIndex++
    }
  }

  for (let index = 0; index < 128; index++) {
    const angle = ((4 * index + 1) * PI) / 1024
    tables.fftFinalSines[index] = clampInt16(
      Math.trunc(Math.sin(angle) * FFT_FIXED_POINT_SCALE)
    )
    tables.fftFinalCosines[index] = clampInt16(
      Math.floor(Math.cos(angle) * FFT_FIXED_POINT_SCALE)
    )
  }
  tables.fftFinalCosines[90] = 14643

  for (let index = 0; index <= 0xff; index++) {
    const gray = index ^ (index >> 1)
    tables.fftGrayBitReversalIndices[index] = reverseLowBits(gray, 8)
  }

  return Object.freeze(tables)
}

let runtimeTables

/**
 * Return the lazily initialized shared ATRAC3 transform tables.
 *
 * @returns {object} Cached immutable transform-table collection.
 */
export function transformTables() {
  runtimeTables ??= buildTransformTables()
  return runtimeTables
}

